import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const IN_JSON = path.join(ROOT, "reports", "external", "official", "knightmodels_gamedata.json");
const IN_META = path.join(ROOT, "reports", "external", "official", "knightmodels_gamedata.meta.json");
const OUT_JS = path.join(ROOT, "official-data.js");
const OUT_REPORT = path.join(ROOT, "reports", "external", "official", "official-reference-report.json");

function readJsonIfExists(file, fallback = null) {
  if (!fs.existsSync(file)) return fallback;
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function findTopLevelValueStart(text, key) {
  let depth = 0;
  let inString = false;
  let escaped = false;

  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (inString) {
      if (escaped) escaped = false;
      else if (ch === "\\") escaped = true;
      else if (ch === "\"") {
        inString = false;
        const value = text.slice(stringStart, i);
        if (depth === 1 && value === key) {
          let j = i + 1;
          while (j < text.length && /\s/.test(text[j])) j += 1;
          if (text[j] === ":") return j + 1;
        }
      }
      continue;
    }

    if (ch === "\"") {
      inString = true;
      var stringStart = i + 1;
    } else if (ch === "{" || ch === "[") {
      depth += 1;
    } else if (ch === "}" || ch === "]") {
      depth -= 1;
    }
  }

  return -1;
}

function findValueSlice(text, key) {
  const start = findTopLevelValueStart(text, key);
  if (start < 0) return null;

  const open = text[start];
  const close = open === "{" ? "}" : open === "[" ? "]" : null;
  if (!close) return null;

  let depth = 0;
  let inString = false;
  let escaped = false;

  for (let i = start; i < text.length; i += 1) {
    const ch = text[i];
    if (inString) {
      if (escaped) escaped = false;
      else if (ch === "\\") escaped = true;
      else if (ch === "\"") inString = false;
      continue;
    }

    if (ch === "\"") inString = true;
    else if (ch === open) depth += 1;
    else if (ch === close) {
      depth -= 1;
      if (depth === 0) return text.slice(start, i + 1);
    }
  }

  return null;
}

function extractSections(text) {
  const sectionOrder = [
    "affiliations",
    "cards",
    "characters",
    "weapons",
    "traits",
    "equipments",
    "equipment",
    "upgrades",
    "ranks",
    "objective_types",
    "trait_types",
    "weapon_traits",
    "weapon_types"
  ];

  const sections = {};
  const incomplete = [];

  for (const key of sectionOrder) {
    const slice = findValueSlice(text, key);
    if (!slice) {
      if (findTopLevelValueStart(text, key) >= 0) incomplete.push(key);
      continue;
    }

    try {
      sections[key] = JSON.parse(slice);
    } catch {
      incomplete.push(key);
    }
  }

  return { sections, incomplete };
}

function summarizeSection(value) {
  if (Array.isArray(value)) {
    return {
      type: "array",
      count: value.length,
      fields: value[0] && typeof value[0] === "object" ? Object.keys(value[0]) : []
    };
  }

  if (value && typeof value === "object") {
    const firstKey = Object.keys(value)[0];
    const firstValue = firstKey ? value[firstKey] : null;
    return {
      type: "object",
      count: Object.keys(value).length,
      fields: firstValue && typeof firstValue === "object" ? Object.keys(firstValue) : []
    };
  }

  return { type: typeof value, count: 0, fields: [] };
}

if (!fs.existsSync(IN_JSON)) {
  throw new Error(`Missing ${IN_JSON}. Run tools/fetch-official-gamedata.mjs first.`);
}

const text = fs.readFileSync(IN_JSON, "utf8");
let complete = false;
let sections = {};
let incomplete = [];

try {
  const data = JSON.parse(text);
  complete = true;
  sections = data;
} catch {
  const extracted = extractSections(text);
  sections = extracted.sections;
  incomplete = extracted.incomplete;
}

const meta = readJsonIfExists(IN_META, {});
const summary = Object.fromEntries(Object.entries(sections).map(([key, value]) => [key, summarizeSection(value)]));

const payload = {
  meta: {
    source: meta?.source || "https://app.knightmodels.com/gamedata/",
    generatedAt: new Date().toISOString(),
    complete,
    sourceBytes: Buffer.byteLength(text, "utf8"),
    sourceDownloadedAt: meta?.downloadedAt || null,
    incompleteSections: incomplete
  },
  summary,
  sections
};

const js = `// Generated by tools/build-official-reference.mjs. Do not edit manually.\n` +
  `// Source is an offline snapshot of https://app.knightmodels.com/gamedata/.\n` +
  `window.KM_OFFICIAL_DATA = ${JSON.stringify(payload, null, 2)};\n`;

fs.writeFileSync(OUT_JS, js, "utf8");
fs.mkdirSync(path.dirname(OUT_REPORT), { recursive: true });
fs.writeFileSync(OUT_REPORT, JSON.stringify({
  generatedAt: payload.meta.generatedAt,
  complete,
  incomplete,
  summary
}, null, 2), "utf8");

console.log(`wrote ${OUT_JS}`);
console.log(JSON.stringify({ complete, incomplete, summary }, null, 2));
